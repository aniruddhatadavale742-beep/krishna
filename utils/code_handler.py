import os
import re
import pyperclip
from datetime import datetime


class CodeHandler:
    """
    Handles code generated by KRISHNA.

    Features:
    - Detects Markdown code blocks
    - Saves code automatically
    - Copies code to Windows clipboard
    - Detects common programming languages
    """

    def __init__(self):

        self.output_folder = "generated_code"

        os.makedirs(
            self.output_folder,
            exist_ok=True
        )

    def extract_code_blocks(self, text):
        """
        Extract code from Markdown code blocks.

        Example:

        ```html
        <h1>Hello</h1>
        ```

        Returns:
            [(language, code)]
        """

        pattern = r"```([a-zA-Z0-9_+-]*)\s*\n?(.*?)```"

        matches = re.findall(
            pattern,
            text,
            re.DOTALL
        )

        return matches

    def detect_extension(self, language, code):
        """
        Determine the correct file extension.
        """

        language = language.lower().strip()

        extensions = {

            "html": ".html",
            "htm": ".html",

            "css": ".css",

            "javascript": ".js",
            "js": ".js",

            "typescript": ".ts",
            "ts": ".ts",

            "python": ".py",
            "py": ".py",

            "java": ".java",

            "c": ".c",

            "cpp": ".cpp",
            "c++": ".cpp",

            "csharp": ".cs",
            "cs": ".cs",

            "php": ".php",

            "json": ".json",

            "xml": ".xml",

            "sql": ".sql",

            "bash": ".sh",
            "shell": ".sh",

            "powershell": ".ps1",
            "ps1": ".ps1",

            "markdown": ".md",
            "md": ".md"
        }

        if language in extensions:

            return extensions[language]

        # Try to recognize HTML even if
        # language wasn't specified.

        if (
            "<html" in code.lower()
            or "<!doctype html" in code.lower()
            or "<body" in code.lower()
        ):
            return ".html"

        return ".txt"

    def save_code(self, language, code):
        """
        Save generated code to a file.
        """

        extension = self.detect_extension(
            language,
            code
        )

        timestamp = datetime.now().strftime(
            "%Y%m%d_%H%M%S"
        )

        filename = (
            f"krishna_code_{timestamp}"
            f"{extension}"
        )

        filepath = os.path.join(
            self.output_folder,
            filename
        )

        with open(
            filepath,
            "w",
            encoding="utf-8"
        ) as file:

            file.write(
                code.strip()
            )

        return filepath

    def copy_to_clipboard(self, code):
        """
        Copy generated code to Windows clipboard.
        """

        try:

            pyperclip.copy(
                code.strip()
            )

            return True

        except Exception:

            return False

    def process_response(self, response):
        """
        Detect and process code inside an AI response.

        Returns:
            Original response
            plus file/clipboard information.
        """

        blocks = self.extract_code_blocks(
            response
        )

        if not blocks:

            return response

        messages = []

        for index, (language, code) in enumerate(
            blocks,
            start=1
        ):

            code = code.strip()

            if not code:
                continue

            filepath = self.save_code(
                language,
                code
            )

            copied = self.copy_to_clipboard(
                code
            )

            messages.append(
                f"\nKRISHNA: Code block {index} saved to:\n"
                f"{filepath}"
            )

            if copied:

                messages.append(
                    "KRISHNA: Code copied to clipboard. "
                    "You can press Ctrl+V to paste it."
                )

        if messages:

            return (
                response
                + "\n"
                + "\n".join(messages)
            )

        return response